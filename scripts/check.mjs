import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const origin = 'https://screeners.ca';
const failures = [];
let checks = 0;
function check(condition, message) {
  checks += 1;
  if (!condition) failures.push(message);
}
function walk(directory) {
  check((fs.statSync(directory).mode & 0o777) === 0o755, `${path.relative(dist, directory) || 'dist'}: public directory permissions must be 755`);
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const resolved = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(resolved) : [resolved];
  });
}
function attrs(tag) {
  const attributes = {};
  for (const match of tag.matchAll(/([\w:-]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+)))?/g)) {
    attributes[match[1].toLowerCase()] = match[2] ?? match[3] ?? match[4] ?? '';
  }
  return attributes;
}
function decode(value) {
  return value.replaceAll('&amp;', '&').replaceAll('&#39;', "'").replaceAll('&quot;', '"');
}
function localFile(url) {
  const clean = decodeURIComponent(url.pathname);
  const candidate = path.resolve(dist, `.${clean}`);
  if (!candidate.startsWith(`${dist}${path.sep}`) && candidate !== dist) return null;
  if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) return candidate;
  const index = path.join(candidate, 'index.html');
  return fs.existsSync(index) ? index : null;
}

assert.ok(fs.existsSync(dist), 'Run npm run build before the static launch checks.');
const files = walk(dist);
for (const file of files) {
  check((fs.statSync(file).mode & 0o777) === 0o644, `${path.relative(dist, file)}: public file permissions must be 644`);
}
const htmlFiles = files.filter(file => file.endsWith('.html'));
assert.ok(htmlFiles.length > 20, 'Expected a complete bilingual static website.');
const pageByUrl = new Map();
const pageRecords = [];
const titles = new Map();
const descriptions = new Map();

for (const filename of htmlFiles) {
  const html = fs.readFileSync(filename, 'utf8');
  const relative = path.relative(dist, filename).replaceAll(path.sep, '/');
  const pathname = `/${relative.replace(/index\.html$/, '')}`;
  const pageUrl = new URL(pathname, origin);
  const isLocalized = /^\/(en|fr)\//.test(pathname);
  const language = pathname.startsWith('/fr/') ? 'fr' : 'en';
  const isError = /(?:^|\/)404(?:\.html|\/)/.test(pathname);
  const noindex = /<meta\b[^>]*\bcontent=["'][^"']*noindex/i.test(html);
  const links = [...html.matchAll(/<link\b[^>]*>/gi)].map(match => attrs(match[0]));
  const canonical = links.find(link => link.rel === 'canonical')?.href;
  const alternates = links.filter(link => link.rel === 'alternate' && link.hreflang);
  const ids = [...html.matchAll(/\bid=["']([^"']+)["']/g)].map(match => match[1]);
  const record = { filename, relative, pathname, html, canonical, alternates, isLocalized, isError, noindex, ids };
  pageRecords.push(record);
  pageByUrl.set(new URL(pathname, origin).href, record);

  check(new Set(ids).size === ids.length, `${relative}: duplicate element IDs`);
  check(/<!doctype html>/i.test(html), `${relative}: missing HTML doctype`);
  check(/<title>[^<]+<\/title>/i.test(html), `${relative}: missing page title`);
  for (const img of html.matchAll(/<img\b[^>]*>/gi)) {
    check('alt' in attrs(img[0]), `${relative}: image missing alt attribute`);
  }
  for (const inline of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    if (attrs(inline[1]).type === 'application/ld+json') {
      try {
        const schema = JSON.parse(inline[2]);
        check(Boolean(schema && typeof schema === 'object'), `${relative}: empty structured data`);
      } catch {
        check(false, `${relative}: malformed JSON-LD`);
      }
    }
  }
  check(!/lorem ipsum|powered by codex|generated by (?:AI|Codex)|design by Grafov/i.test(html), `${relative}: temporary or prohibited credit copy`);
  check(!/(?:googletagmanager\.com|google-analytics\.com|connect\.facebook\.net|hotjar\.com)/i.test(html), `${relative}: unreviewed tracker`);

  if (!isLocalized || isError) continue;
  check((html.match(/<h1(?:\s|>)/gi) ?? []).length === 1, `${relative}: expected exactly one H1`);
  const htmlTag = attrs(html.match(/<html\b[^>]*>/i)?.[0] ?? '');
  check(htmlTag.lang === language || htmlTag.lang === `${language}-CA`, `${relative}: wrong document language`);
  const metas = [...html.matchAll(/<meta\b[^>]*>/gi)].map(match => attrs(match[0]));
  const description = metas.find(meta => meta.name === 'description')?.content;
  check(Boolean(description?.trim()), `${relative}: missing meta description`);
  check(Boolean(metas.find(meta => meta.name === 'viewport')), `${relative}: missing mobile viewport`);
  check(canonical === pageUrl.href, `${relative}: expected canonical ${pageUrl.href}, found ${canonical}`);
  for (const lang of ['en-CA', 'fr-CA']) {
    const alternate = alternates.find(link => link.hreflang === lang);
    check(Boolean(alternate?.href?.startsWith(`${origin}/${lang.slice(0, 2)}/`)), `${relative}: missing ${lang} alternate`);
  }
  const title = html.match(/<title>([^<]+)<\/title>/i)?.[1];
  if (!noindex) {
    check(!titles.has(title), `${relative}: title duplicates ${titles.get(title)}`);
    check(!descriptions.has(description), `${relative}: description duplicates ${descriptions.get(description)}`);
    titles.set(title, relative);
    descriptions.set(description, relative);
  }
  check(html.includes('tel:+18336969996'), `${relative}: approved telephone link missing`);
  check(html.includes('mailto:info@screeners.ca'), `${relative}: approved email link missing`);
  check(html.includes('SCREENERS.CA'), `${relative}: integrated brand missing`);
  check(html.includes('<nav'), `${relative}: shared navigation missing`);
  check(html.includes('<footer'), `${relative}: shared footer missing`);
  const header = html.match(/<header\b[^>]*>[\s\S]*?<\/header>/i)?.[0] ?? '';
  const navigation = [...header.matchAll(/<nav\b[^>]*>([\s\S]*?)<\/nav>/gi)].map(match => match[1]).join(' ');
  const menuText = navigation.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').toUpperCase();
  const labels = language === 'en'
    ? [/EQUIPMENT/, /RENTALS/, /PARTS/, /SERVICES/, /INDUSTRIES/, /LOCATIONS/, /CONTACT/]
    : [/ÉQUIPEMENTS?/, /LOCATIONS?/, /PIÈCES/, /SERVICES/, /INDUSTRIES/, /RÉGIONS|EMPLACEMENTS/, /CONTACT/];
  for (const label of labels) check(label.test(menuText), `${relative}: primary navigation missing ${label}`);
  check(!/<a\b[^>]*href=["'][^"']*\/(?:about|a-propos)\/?["']/i.test(navigation), `${relative}: About belongs in the footer, not primary navigation`);
}

for (const page of pageRecords) {
  for (const match of page.html.matchAll(/<(?:a|img|script|link|source|form)\b[^>]*>/gi)) {
    const tag = attrs(match[0]);
    const references = [tag.href, tag.src, tag.action];
    if (tag.srcset) references.push(...tag.srcset.split(',').map(item => item.trim().split(/\s+/)[0]));
    for (const reference of references.filter(Boolean)) {
      if (/^(?:mailto:|tel:|data:|javascript:)/i.test(reference)) continue;
      let url;
      try { url = new URL(decode(reference), new URL(page.pathname, origin)); } catch { check(false, `${page.relative}: malformed reference ${reference}`); continue; }
      if (url.origin !== origin) continue;
      const target = localFile(url);
      check(Boolean(target), `${page.relative}: broken local reference ${reference}`);
      if (tag.src === reference && /^<script/i.test(match[0]) && target && /\.(?:m?js)$/.test(target)) {
        const script = fs.readFileSync(target, 'utf8');
        if (/^\s*(?:import|export)\s/m.test(script)) {
          check(tag.type === 'module', `${page.relative}: ES module script ${reference} needs type="module"`);
        }
      }
      if (target?.endsWith('.html') && url.hash) {
        const targetHtml = fs.readFileSync(target, 'utf8');
        const fragment = decodeURIComponent(url.hash.slice(1));
        check(targetHtml.includes(`id="${fragment}"`) || targetHtml.includes(`id='${fragment}'`), `${page.relative}: missing anchor ${reference}`);
      }
    }
  }
  if (!page.isLocalized || page.isError) continue;
  for (const alternate of page.alternates.filter(link => ['en-CA', 'fr-CA'].includes(link.hreflang))) {
    const other = pageByUrl.get(alternate.href);
    check(Boolean(other), `${page.relative}: alternate target does not exist ${alternate.href}`);
    check(Boolean(other?.alternates.some(link => link.href === page.canonical)), `${page.relative}: alternate is not reciprocal ${alternate.href}`);
  }
  for (const form of page.html.matchAll(/<form\b([^>]*)>([\s\S]*?)<\/form>/gi)) {
    const formAttributes = attrs(form[1]);
    const body = form[2];
    check((formAttributes.method ?? '').toLowerCase() === 'post', `${page.relative}: quote form must POST`);
    const controls = [...body.matchAll(/<(?:input|select|textarea)\b[^>]*>/gi)].map(match => attrs(match[0]));
    for (const name of ['name', 'company', 'email', 'phone', 'province', 'city', 'inquiry_type', 'equipment_type', 'material', 'throughput', 'timeline', 'delivery_location', 'description', 'consent', 'lang']) {
      check(controls.some(control => control.name === name), `${page.relative}: quote field ${name} missing`);
    }
    check(!('required' in (controls.find(control => control.name === 'throughput') ?? {})), `${page.relative}: throughput must remain optional`);
    for (const control of controls.filter(item => item.type !== 'hidden' && item.type !== 'submit')) {
      const escapedId = (control.id ?? '').replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      check(Boolean(control.id && new RegExp(`<label\\b[^>]*\\bfor=["']${escapedId}["']`, 'i').test(body)), `${page.relative}: control ${control.name} missing associated label`);
    }
    const consent = controls.find(item => item.type === 'checkbox' && /consent/i.test(item.name ?? ''));
    check(Boolean(consent && 'required' in consent), `${page.relative}: required consent checkbox missing`);
    const email = controls.find(item => item.type === 'email');
    check(Boolean(email && 'required' in email), `${page.relative}: email must be required`);
    check(Boolean(controls.find(item => /website|honeypot|company_url|fax/i.test(item.name ?? ''))), `${page.relative}: anti-spam honeypot missing`);
    check(/aria-live=|role=["'](?:status|alert)/i.test(body), `${page.relative}: accessible form feedback missing`);
  }
}

for (const filename of files.filter(file => /\.(?:m?js)$/.test(file))) {
  const source = fs.readFileSync(filename, 'utf8');
  const scriptUrl = new URL(`/${path.relative(dist, filename).replaceAll(path.sep, '/')}`, origin);
  for (const match of source.matchAll(/(?:import|export)\s+(?:[^'";]+?\s+from\s+)?['"]([^'"]+)['"]/g)) {
    const specifier = match[1];
    if (!specifier.startsWith('.') && !specifier.startsWith('/')) continue;
    check(Boolean(localFile(new URL(specifier, scriptUrl))), `${path.relative(dist, filename)}: imported module missing ${specifier}`);
  }
}

const sitemapPath = path.join(dist, 'sitemap.xml');
check(fs.existsSync(sitemapPath), 'sitemap.xml missing');
if (fs.existsSync(sitemapPath)) {
  const sitemap = fs.readFileSync(sitemapPath, 'utf8');
  const locations = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map(match => decode(match[1]));
  check(new Set(locations).size === locations.length, 'sitemap has duplicate locations');
  for (const page of pageRecords.filter(item => item.isLocalized && !item.isError && !item.noindex)) {
    check(locations.includes(page.canonical), `${page.relative}: indexable page missing from sitemap`);
  }
  for (const url of locations) {
    check(Boolean(pageByUrl.get(url)), `sitemap contains nonexistent content page ${url}`);
  }
}
const robotsPath = path.join(dist, 'robots.txt');
check(fs.existsSync(robotsPath), 'robots.txt missing');
if (fs.existsSync(robotsPath)) {
  check(fs.readFileSync(robotsPath, 'utf8').includes(`${origin}/sitemap.xml`), 'robots.txt must reference production sitemap');
}
check(files.some(file => /(?:^|\/)404(?:\.html|\/index\.html)$/.test(file)), '404 page missing');
check(!files.some(file => /(?:^|\/)(?:\.env(?:\..*)?|screeners-quote-config\.php)$/.test(file)), 'Private environment/configuration file must not be packaged into the public document root');

if (failures.length) {
  console.error(`Static launch checks failed (${failures.length}/${checks}):\n${failures.map(failure => `- ${failure}`).join('\n')}`);
  process.exitCode = 1;
} else {
  console.log(`Static launch checks passed: ${checks} assertions across ${htmlFiles.length} HTML documents.`);
  console.log('Browser rendering, keyboard interaction, live hosting and actual email delivery remain separate verification steps.');
}
